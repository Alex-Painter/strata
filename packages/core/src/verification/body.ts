/**
 * Reads the proof an author wrote into a PR body: the sections under headings
 * such as Verification, Testing and Screenshots. Pure text rules, no LLM.
 *
 * What it takes:
 * - images and videos, captioned by their alt text or the line above them;
 * - an end-to-end verdict in inline code, such as `feed-e2e shots=28 failures=0`;
 * - "Not run:" or "Not yet verified:" lines and the bullets under them;
 * - bullets that name test commands or tests, and other bullets as notes;
 * - numbered manual steps, as one note.
 *
 * Everything it reads is a claim: only the PR body says so.
 */
import { stableId } from "../model/ids.js";
import type { VerificationItem, VerificationKind } from "../model/verification.js";

/** Headings whose sections hold verification. Parents count: "### Automated tests" under "## Verification". */
const VERIFY_HEADING =
  /verif|test|screenshot|screen ?shot|recording|video|demo|before.+after|\bqa\b|proof|evidence|how (i|we) checked|validation/i;
const AUTOMATED_HEADING = /automated|unit|integration|tests? added|new tests/i;
const MANUAL_HEADING = /manual/i;
const GAP_HEADING = /not (yet )?(run|verified|tested)|unverified|could ?n[o']t verify|gaps?/i;

/** A line that opens a list of things the author did not verify. */
const GAP_LINE =
  /^(?:\*\*|__)?(not (?:yet )?(?:run|verified|tested)|unverified|could ?n[o']t (?:verify|test|run)|did ?n[o']t (?:verify|test|run))\b[^:]*:(?:\*\*|__)?\s*(.*)$/i;

/** A bullet that is about running tests or checks. */
const TEST_WORDS =
  /pytest|vitest|jest|mocha|playwright|cypress|\btsc\b|pyright|mypy|ruff|eslint|biome|lint|typecheck|type check|vulture|pre-commit|\bsuite\b|\btests?\b|test_\w+|\bspec\b|go test|cargo test|pnpm test|npm test|uv run/i;

/** Text that ends the author's part of the body: tool footers. */
const FOOTERS = [
  "<!-- CURSOR_AGENT_PR_BODY_END -->",
  "<!-- codesmith:footer -->",
  "<!-- Generated by",
];

const VIDEO_EXT = /\.(mp4|mov|webm|m4v)(\?|#|$)/i;
/** GitHub renders a bare uploaded-asset link on its own line as a video. */
const GITHUB_ASSET = /^https:\/\/github\.com\/user-attachments\/assets\/[\w-]+$/;

interface Section {
  /** The heading path, outermost first. */
  headings: string[];
  lines: string[];
}

export function parsePrBody(pr: number, body: string | null, url?: string): VerificationItem[] {
  if (!body) return [];
  const items: VerificationItem[] = [];
  const seen = new Set<string>();
  const add = (item: Omit<VerificationItem, "id" | "pr" | "source" | "strength" | "commit">) => {
    const id = stableId(
      "ver",
      String(pr),
      item.kind,
      item.title,
      item.media?.url ?? "",
      item.section ?? "",
    );
    if (seen.has(id)) return;
    seen.add(id);
    items.push({
      id,
      pr,
      source: "pr-body",
      // A picture or video a reviewer can open is more than words.
      strength: item.media ? "attached" : "claimed",
      commit: null,
      ...(url ? { url } : {}),
      ...item,
    });
  };

  for (const section of sections(clean(body))) {
    const relevant = section.headings.some((h) => VERIFY_HEADING.test(h));
    const name = section.headings[section.headings.length - 1] ?? "";
    const gapSection = section.headings.some((h) => GAP_HEADING.test(h));
    if (!relevant && !gapSection) {
      // Walk verdicts and media outside the named sections are still proof, if rarer.
      for (const walk of walks(section.lines.join("\n"))) add({ ...walk, section: name });
      continue;
    }
    readSection(section, name, gapSection, add);
  }
  return items;
}

type Add = (item: Omit<VerificationItem, "id" | "pr" | "source" | "strength" | "commit">) => void;

function readSection(section: Section, name: string, gapSection: boolean, add: Add) {
  const automated = section.headings.some((h) => AUTOMATED_HEADING.test(h));
  const manual = section.headings.some((h) => MANUAL_HEADING.test(h));
  const blocks = listBlocks(section.lines);
  let previousText = "";
  let inGapList = gapSection;
  const steps: string[] = [];

  for (const block of blocks) {
    const text = block.text;
    for (const walk of walks(text)) add({ ...walk, section: name });

    const media = mediaIn(text);
    for (const m of media) {
      const caption =
        m.alt || stripMarkdown(previousText) || (m.type === "video" ? "Recording" : "Screenshot");
      const pairing = /^\s*before\b/i.test(caption)
        ? "before"
        : /^\s*after\b/i.test(caption)
          ? "after"
          : undefined;
      add({
        kind: m.type === "video" ? "recording" : "screenshot",
        title: oneLine(caption),
        result: "claimed",
        media: { type: m.type, url: m.url },
        section: name,
        ...(pairing ? { pairing } : {}),
      });
    }
    if (media.length > 0) {
      previousText = "";
      continue;
    }

    if (block.kind === "paragraph") {
      const gap = GAP_LINE.exec(stripMarkdown(text));
      if (gap) {
        inGapList = true;
        const rest = gap[2]?.trim();
        if (rest) add({ kind: "not-run", title: oneLine(rest), result: "not-run", section: name });
      } else if (!gapSection) {
        inGapList = false;
      }
      previousText = text;
      continue;
    }

    // A list item.
    const item = stripMarkdown(block.text);
    if (!item) continue;
    if (inGapList) {
      add({ kind: "not-run", title: oneLine(item), result: "not-run", section: name });
    } else if (manual && block.kind === "ordered") {
      steps.push(item);
    } else if (automated || TEST_WORDS.test(item)) {
      add(claim("test", item, name, block.children));
    } else {
      add(claim("note", item, name, block.children));
    }
    previousText = "";
  }

  if (steps.length > 0) {
    add({
      kind: "note",
      title: `Manual test: ${steps.length === 1 ? "1 step" : `${steps.length} steps`}`,
      detail: steps.map((step, i) => `${i + 1}. ${step}`).join("\n"),
      result: "claimed",
      section: name,
    });
  }
}

function claim(kind: VerificationKind, text: string, section: string, children: string[]) {
  const title = oneLine(text);
  const extra = [text.length > title.length ? text : "", ...children.map(stripMarkdown)]
    .filter(Boolean)
    .join("\n");
  return {
    kind,
    title,
    result: "claimed" as const,
    section,
    ...(extra ? { detail: extra } : {}),
  };
}

/** Inline code with a failure count, such as `feed-e2e shots=28 failures=0 forecast-move=/deals`. */
function walks(text: string) {
  const found: Omit<VerificationItem, "id" | "pr" | "source" | "strength" | "commit">[] = [];
  for (const match of text.matchAll(/`([^`\n]*\bfail(?:ures|ed|s)?=(\d+)[^`\n]*)`/g)) {
    const failures = Number(match[2]);
    found.push({
      kind: "walk",
      title: match[1] as string,
      result: failures === 0 ? "pass" : "fail",
    });
  }
  return found;
}

/** Cuts tool footers, HTML comments and badge pictures out of the body. */
function clean(body: string): string {
  let text = body.replace(/\r\n/g, "\n");
  for (const footer of FOOTERS) {
    const at = text.indexOf(footer);
    if (at >= 0) text = text.slice(0, at);
  }
  return text
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<picture>[\s\S]*?<\/picture>/gi, "")
    .replace(/```[\s\S]*?```/g, (block) => block.replace(/!\[/g, "!​["));
}

function sections(text: string): Section[] {
  const out: Section[] = [{ headings: [], lines: [] }];
  const stack: { level: number; title: string }[] = [];
  for (const line of text.split("\n")) {
    const heading = /^(#{1,6})\s+(.*?)\s*#*\s*$/.exec(line);
    if (heading) {
      const level = (heading[1] as string).length;
      while (stack.length > 0 && (stack[stack.length - 1] as { level: number }).level >= level)
        stack.pop();
      stack.push({ level, title: stripMarkdown(heading[2] as string) });
      out.push({ headings: stack.map((h) => h.title), lines: [] });
      continue;
    }
    (out[out.length - 1] as Section).lines.push(line);
  }
  return out.filter((section) => section.lines.some((line) => line.trim()));
}

interface Block {
  kind: "paragraph" | "bullet" | "ordered";
  text: string;
  /** Nested bullets under a list item. */
  children: string[];
}

/** Paragraphs and top-level list items; nested items go with their parent. */
function listBlocks(lines: string[]): Block[] {
  const blocks: Block[] = [];
  let current: Block | null = null;
  for (const raw of lines) {
    if (!raw.trim()) {
      if (current?.kind === "paragraph") current = null;
      continue;
    }
    const top = /^(?:[-*+]|(\d+)[.)])\s+(.*)$/.exec(raw);
    const nested = /^\s{2,}(?:[-*+]|\d+[.)])\s+(.*)$/.exec(raw);
    if (top) {
      current = { kind: top[1] ? "ordered" : "bullet", text: top[2] as string, children: [] };
      blocks.push(current);
    } else if (nested && current && current.kind !== "paragraph") {
      current.children.push(nested[1] as string);
    } else if (current && /^\s+\S/.test(raw) && current.kind !== "paragraph") {
      current.text += ` ${raw.trim()}`;
    } else if (current?.kind === "paragraph") {
      current.text += `\n${raw.trim()}`;
    } else {
      current = { kind: "paragraph", text: raw.trim(), children: [] };
      blocks.push(current);
    }
  }
  return blocks;
}

function mediaIn(text: string): { type: "image" | "video"; url: string; alt: string }[] {
  const found: { type: "image" | "video"; url: string; alt: string; at: number }[] = [];
  for (const m of text.matchAll(/!\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+"[^"]*")?\s*\)/g)) {
    const url = m[2] as string;
    found.push({
      type: VIDEO_EXT.test(url) ? "video" : "image",
      url,
      alt: (m[1] ?? "").trim(),
      at: m.index ?? 0,
    });
  }
  for (const m of text.matchAll(/<(img|video|source)\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi)) {
    const tag = (m[1] as string).toLowerCase();
    const alt = /\balt=["']([^"']*)["']/i.exec(m[0])?.[1] ?? "";
    const url = m[2] as string;
    found.push({
      type: tag === "img" && !VIDEO_EXT.test(url) ? "image" : "video",
      url,
      alt: alt.trim(),
      at: m.index ?? 0,
    });
  }
  for (const line of text.split("\n")) {
    const bare = line.trim();
    if (GITHUB_ASSET.test(bare) || (/^https?:\/\/\S+$/.test(bare) && VIDEO_EXT.test(bare))) {
      found.push({ type: "video", url: bare, alt: "", at: text.indexOf(bare) });
    }
  }
  return found
    .filter((m) => /^https?:\/\//.test(m.url))
    .sort((a, b) => a.at - b.at)
    .map(({ at: _at, ...m }) => m);
}

/** Plain text: no emphasis, links as their text, code as its text. */
export function stripMarkdown(text: string): string {
  return text
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/<[^>]+>/g, "")
    .replace(/(\*\*|__)(.*?)\1/g, "$2")
    .replace(/(^|\W)[*_]([^*_\n]+)[*_](?=\W|$)/g, "$1$2")
    .replace(/\s+/g, " ")
    .trim();
}

/** The first sentence or 160 characters, for a title. */
function oneLine(text: string): string {
  const flat = text.replace(/\s+/g, " ").trim();
  if (flat.length <= 160) return flat;
  const cut = flat.slice(0, 160);
  const stop = cut.lastIndexOf(". ");
  return stop > 60 ? cut.slice(0, stop + 1) : `${cut.slice(0, cut.lastIndexOf(" "))}…`;
}
